#!/usr/bin/env python3
"""Generate a cheapest-first routing setup from eval-models results.

Usage:
  python3 make_routing.py --results results.json --out routing/ \
      [--guards guards.json] [--chain id1,id2] [--include-unknown-cost]

Writes to --out:
  routing.json         chain + settings + guards (no secrets, env var names only)
  router.py, mf_core.py  standalone runtime router (escalates on errors and failed guards)
  litellm.config.yaml  LiteLLM proxy config (fallbacks fire on API errors only)
  ROUTING.md           what was generated and why

Nothing is deployed or applied. Exit codes: 0 ok, 2 invalid input.
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import mf_core as core  # noqa: E402

LITELLM_PREFIX = {"anthropic": "anthropic", "openai": "openai", "gemini": "gemini",
                  "openai_compatible": "openai"}
LITELLM_DOCS = "https://docs.litellm.ai/docs/proxy/reliability"


def _q(value: str) -> str:
    """Quote a scalar for YAML; JSON strings are valid YAML double-quoted scalars."""
    return json.dumps(value)


def build_chain(results: Dict[str, Any], manual: Optional[List[str]],
                include_unknown: bool) -> Tuple[List[str], List[str]]:
    """Return (chain, dropped).

    Automatic chains form a cascade: sorted by cost per passing call, keeping a
    model only if it is more reliable than every cheaper model before it. A model
    that costs more per pass without being more reliable is dominated and dropped.
    """
    rows = {r["id"]: r for r in results.get("summary", [])}
    if manual:
        unknown = [i for i in manual if i not in rows]
        if unknown:
            raise core.ConfigError(f"--chain names ids not in results: {unknown}")
        return manual, []
    passing = [r for r in rows.values() if r.get("meets_threshold")]
    priced = sorted((r for r in passing if r.get("cost_known")),
                    key=lambda r: (r["cost_per_pass_usd"] if r.get("cost_per_pass_usd") is not None
                                   else float("inf"), -r["pass_rate"]))
    chain: List[str] = []
    dropped: List[str] = []
    best_rate = -1.0
    for row in priced:
        if row["pass_rate"] > best_rate:
            chain.append(row["id"])
            best_rate = row["pass_rate"]
        else:
            dropped.append(row["id"])
    if include_unknown:
        chain += [r["id"] for r in passing if not r.get("cost_known")]
    if not chain:
        raise core.ConfigError("No candidate met the threshold with a known cost. Re-run the eval, "
                               "add verified prices, pass --include-unknown-cost, or set --chain.")
    return chain, dropped


def litellm_yaml(chain: List[core.Candidate], timeout_s: float) -> str:
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    lines = [
        "# Generated by Model Finder. Review before use; nothing has been deployed.",
        f"# Syntax follows {LITELLM_DOCS} (checked 2026-10-13). Re-verify against current docs.",
        "# LiteLLM fallbacks trigger on API errors (rate limits, outages, timeouts),",
        "# NOT on low-quality answers. Use router.py guards for quality-based escalation.",
        f"# Generated {stamp}.",
        "model_list:",
    ]
    for cand in chain:
        lines += [f"  - model_name: {_q(cand.id)}", "    litellm_params:",
                  f"      model: {_q(LITELLM_PREFIX[cand.provider] + '/' + cand.model)}"]
        if cand.api_key_env:
            lines.append(f"      api_key: {_q('os.environ/' + cand.api_key_env)}")
        if cand.provider == "openai_compatible":
            lines.append(f"      api_base: {_q(cand.base_url + '/v1')}")
        elif cand.base_url != core.DEFAULT_BASE_URLS[cand.provider]:
            lines.append(f"      api_base: {_q(cand.base_url)}")
    lines += ["litellm_settings:", "  num_retries: 2", f"  request_timeout: {int(timeout_s)}"]
    if len(chain) > 1:
        fallback = {chain[0].id: [c.id for c in chain[1:]]}
        lines.append(f"  fallbacks: [{json.dumps(fallback)}]")
    return "\n".join(lines) + "\n"


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--results", type=Path, required=True)
    parser.add_argument("--out", type=Path, default=Path("routing"))
    parser.add_argument("--guards", type=Path, help='JSON file: {"checks": [...]} applied to every reply')
    parser.add_argument("--chain", help="explicit comma-separated order, overriding cost order")
    parser.add_argument("--include-unknown-cost", action="store_true")
    parser.add_argument("--pii-policy", choices=("block", "warn", "off"), default="warn",
                        help="router behaviour when a prompt contains detected personal data or secrets")
    args = parser.parse_args(argv)

    try:
        results = json.loads(args.results.read_text(encoding="utf-8"))
        if not isinstance(results, dict) or results.get("schema") != "model-finder-eval/1":
            raise core.ConfigError("--results must be a results.json written by eval_models.py.")
        cands = {c["id"]: core.validate_candidate(c, i) for i, c in enumerate(results.get("candidates", []))}
        settings_raw = results.get("settings") or {}
        core.validate_settings(settings_raw)
        guards: List[Dict[str, Any]] = []
        if args.guards:
            graw = json.loads(args.guards.read_text(encoding="utf-8"))
            guards = core.validate_checks((graw or {}).get("checks"), "guards", allow_empty=True)
        manual = [x.strip() for x in args.chain.split(",") if x.strip()] if args.chain else None
        order, dropped = build_chain(results, manual, args.include_unknown_cost)
        chain = [cands[i] for i in order]
    except (core.ConfigError, OSError, json.JSONDecodeError, KeyError) as exc:
        print(f"Input error: {exc}", file=sys.stderr)
        return 2

    notes: List[str] = []
    if dropped:
        notes.append(f"Dropped as dominated (costlier per pass, not more reliable): {', '.join(dropped)}. "
                     "Add one back with --chain if you want an extra fallback for provider outages.")
    if len(chain) == 1:
        notes.append("Only one model in the chain: there is no fallback.")
    if not guards:
        notes.append("No guards supplied: the router escalates only on errors and empty replies, "
                     "so it cannot detect wrong-but-well-formed answers.")
    routing = {
        "schema": "model-finder-routing/1",
        "generated_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "source_results": results.get("started_utc"),
        "settings": settings_raw,
        "chain": [c.public_dict() for c in chain],
        "guards": guards,
        "pii_policy": args.pii_policy,
        "notes": notes,
    }
    try:
        args.out.mkdir(parents=True, exist_ok=True)
        (args.out / "routing.json").write_text(json.dumps(routing, indent=2), encoding="utf-8")
        shutil.copyfile(HERE.parent / "assets" / "router.py", args.out / "router.py")
        shutil.copyfile(HERE / "mf_core.py", args.out / "mf_core.py")
        (args.out / "litellm.config.yaml").write_text(
            litellm_yaml(chain, float(settings_raw.get("timeout_s", 60))), encoding="utf-8")
        rows = {r["id"]: r for r in results.get("summary", [])}
        doc = ["# Routing plan", "", "Cascade (lowest cost per passing call first; each step is more reliable):", ""]
        for pos, cand in enumerate(chain, 1):
            r = rows.get(cand.id, {})
            rate = r.get("pass_rate")
            cost = r.get("total_cost_usd")
            doc.append(f"{pos}. **{cand.id}** (`{cand.model}`): eval pass rate "
                       f"{'n/a' if rate is None else f'{rate:.0%}'}, eval cost "
                       f"{'unknown' if cost is None else f'${cost:.6f}'}")
        doc += ["", f"Guards: {len(guards)} check(s) on every reply.",
                f"Personal-data policy: {args.pii_policy} (block = never send prompts with detected "
                "personal data or secrets; warn = send and report categories; off = no check).", ""]
        doc += [f"- {n}" for n in notes]
        doc += ["", "Run: `python3 router.py routing.json \"your prompt\"`.",
                "LiteLLM: `litellm --config litellm.config.yaml` (error-based fallbacks only).",
                "Nothing has been deployed. Monitor escalation rate and cost in production."]
        (args.out / "ROUTING.md").write_text("\n".join(doc) + "\n", encoding="utf-8")
    except OSError as exc:
        print(f"Could not write output: {exc}", file=sys.stderr)
        return 2
    print(f"Chain: {' -> '.join(c.id for c in chain)}. Wrote {args.out}/")
    for note in notes:
        print(f"Note: {note}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
